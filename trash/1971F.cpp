ll csq(ll x)
{
	return (ll)ceil(sqrtl(x));
}

void solve()
{
	ll r; cin>>r;
	ll ans = 0;
	for(ll x = -r; x <= r; x++)
	{
		ans += 2 * (csq((r+1)*(r+1)-x*x)-csq(r*r-x*x));
		// debug(ans);
	}
	cout<<ans-2<<endl;
}

