void solve()
{
	lli a,b,x;
	cin >> a >> b >> x;
	lli ans = LLONG_MAX;
	int c = 0;
	while(a!=b)
	{
		if(a>b)swap(a,b);
		ans = min(ans, c+b-a);
		b/=x;
		c++;
	}
	ans = min(ans, c+b-a);
	cout<<ans<<"\n";
}

