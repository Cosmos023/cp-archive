void solve()
{
	int n;
	cin >> n;
	string s; cin>>s;
	int i = 0;
	int ans = 0;
	while(i<n)
	{
		if(s[i]=='*')
		{
			i++; continue;
		}
		int j = i+1;
		while(j<n && s[j]=='#') j++;
		ans = max(ans, (j-i+1)/2);
		i=j;
	}
	cout<<ans<<endl;
}

