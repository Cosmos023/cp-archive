void solve()
{
	string s; cin>>s;
	int n = s.size();
	vi delta(n, -1);
	int d = 0;
	for(int i = 0; i<n; i++)
	{
		if(s[i]='+') d++;
		if(s[i]='-') d--;
		delta[i]=d;
	}
}

