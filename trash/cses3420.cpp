void solve()
{
	int n;
	cin >> n;
	vector<int> a(n+1, 0);
	for(int i=0; i<n; i++) cin >> a[i+1];
	int left = 0;
	map<int, int> M;
	ll ans = 0;
	for(int i=1; i<=n; i++)
	{
		left = max(left, M[a[i]]);
		ll k = i-left;
		ans += k;
		M[a[i]] = i;
	}
	cout<<ans<<endl;
}

